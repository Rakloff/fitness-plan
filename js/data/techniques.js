// Техника упражнений. Контракт: app/ARCHITECTURE.md.
// SVG рисуются собственными схемами (человечек из линий), цвет через currentColor.

const r = (n) => Math.round(n * 10) / 10;
const pts = (...a) => a.map((p) => `${r(p[0])},${r(p[1])}`).join(' ');

// Человечек: n шея/плечо, h таз, k колено, f стопа, e локоть, w кисть, x доп. элементы
function body(p) {
  if (p.raw) return p.raw;
  const [nx, ny] = p.n;
  const [hx, hy] = p.h;
  const dx = nx - hx;
  const dy = ny - hy;
  const d = Math.hypot(dx, dy) || 1;
  let s = `<circle cx="${r(nx + (dx / d) * 11)}" cy="${r(ny + (dy / d) * 11)}" r="7"/>`;
  s += `<polyline points="${pts(p.n, p.h, p.k, p.f)}"/>`;
  s += `<polyline points="${pts(p.n, p.e, p.w)}"/>`;
  return s + (p.x || '');
}

// Трос (тонкая линия) и ручка
const cab = (a, b) => `<line x1="${a[0]}" y1="${a[1]}" x2="${b[0]}" y2="${b[1]}" stroke-width="1.5" opacity=".7"/><circle cx="${b[0]}" cy="${b[1]}" r="3" fill="currentColor"/>`;
const FL = '<polyline points="50,74 56,92 58,112"/>'; // вторая нога для вида спереди

function svg(label, eq, poses) {
  let s = `<svg viewBox="0 0 300 120" xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round" role="img" aria-label="${label}">`;
  s += '<path d="M100 6V114M200 6V114" stroke-width="1" opacity=".2"/>';
  poses.forEach((p, i) => {
    s += `<g transform="translate(${i * 100} 0)"><g opacity=".45" stroke-width="4"><path d="M4 114H96" stroke-width="2"/>${eq}</g>${body(p)}</g>`;
  });
  return s + '</svg>';
}

